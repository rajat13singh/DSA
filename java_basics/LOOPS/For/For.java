import java.util.*;
public class For {
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        System.out.println("enter the value of N:");
        int N=sc.nextInt();//value limit by the user
        int i; //iterator
        for(i=1;i<=N;i++){
            System.out.println(i);
        }
    sc.close();
    }
    
}
