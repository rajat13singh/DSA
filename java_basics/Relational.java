public class Relational {
    public static void main(String[] args) {
        //equallity operator>>(==,!=)
        //relational operator>>(<,>,<=,>=)
        //logical operator>>(&&(and),||(or))
        int age = 20;
        int marks = 75;
        int attendance = 80;

        System.out.println(
        (age >= 18 && age <= 25) &&
        (marks == 75 || marks != 40) &&
        attendance >= 75
);
    }
    
}
