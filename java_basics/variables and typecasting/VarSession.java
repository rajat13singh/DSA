public class VarSession{
    public static void main(String[] args) {
        System.out.println(1+3); //directly calculated by the compiler
        //for variable to be stored we should use datatypes
        int x=100;
        System.out.println(x);
        int y; //declaring the variable
        y=44;// initializing the variable
        x=12;//we can change the the values 
        int a=66;
        System.out.println(a);
        System.out.println(x);
        System.out.println(y);
        byte b=127;
        System.out.println(b);
        short c=22435;
        System.out.println(c);
        long d=12122233243L;
        System.out.println(d);
        //byte<short<int<long//
    //Floating DataTypes//
    //float,Double
    float u=98.99f;
    System.out.println(u);
    double avg=98.00223321;
    System.out.println(avg);    
    char ch='w';
    System.out.println(ch);
//boolean datatype
    boolean righttovote=true;
    System.out.println(righttovote);


    }
}
