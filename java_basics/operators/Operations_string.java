public class Operations_string {
    public static void main(String[] args){
        String FirstName="Rajat";
        String LastName="Singh";
        String FullName=FirstName+" "+LastName; //space also counted in concatination
        System.out.println(FullName);
        //we can also add numbers with the string as system will implicitly convert number into string and then concatination will be seen
        //unary operators>>>>>(+,++,--,-,!)
        int a=1;
        a++;//postfixx
        System.out.println(a);
        int b=3;
        ++b;
        System.out.println(b);
    }
    
}
